"""Render the REAL panel with a real engine payload and a buy verdict that carries a trade link.

The DOM check in check_buy_verdict.py proves the button is built; this proves it is on screen, in the card a
player actually sees. The payload comes from docs/mockups/panel-real.html (generated by gen_payload.py from the
engine), and the page comes from overlay/Ui/panel.html, so neither the data nor the markup is a hand-written
copy that could drift.

    python tools/gen_buy_link_preview.py
"""

import io
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAGE = os.path.join(ROOT, "overlay", "Ui", "panel.html")
MOCK = os.path.join(ROOT, "docs", "mockups", "panel-real.html")
TARGET = os.path.join(os.environ.get("TEMP", "."), "panel-buy-link.html")
SHOT = os.path.join(ROOT, "docs", "live-trade-link.png")
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

with io.open(PAGE, encoding="utf-8") as handle:
    page = handle.read()
with io.open(MOCK, encoding="utf-8") as handle:
    mock = handle.read()

# The mockup already carries the engine payload and shows the step tab; take its driver, not its old markup.
match = re.search(r"<script>window\.onload=function\(\)\{.*?\};</script>", mock, re.S)
if not match:
    raise SystemExit("the payload driver is not in panel-real.html - run tools/gen_payload.py first")
driver = match.group(0)

# A verdict of the shape the host sends, with the trade search that produced the price.
verdict = (
    '{"verdict":"buy","text":"\\u041f\\u043e\\u043a\\u0443\\u043f\\u0430\\u0439\\u0442\\u0435: '
    '\\u0433\\u043e\\u0442\\u043e\\u0432\\u044b\\u0439 \\u043f\\u0440\\u0435\\u0434\\u043c\\u0435\\u0442 '
    '\\u0434\\u0435\\u0448\\u0435\\u0432\\u043b\\u0435 \\u043a\\u0440\\u0430\\u0444\\u0442\\u0430 '
    '\\u043f\\u0440\\u0438\\u043c\\u0435\\u0440\\u043d\\u043e \\u043d\\u0430 80%."'
    ',"line":"\\u041a\\u0440\\u0430\\u0444\\u0442 ~0.11 \\u0445\\u0430\\u043e\\u0441\\u0430 '
    '\\u00b7 \\u0433\\u043e\\u0442\\u043e\\u0432\\u044b\\u0439 0.02 \\u0445\\u0430\\u043e\\u0441\\u0430"'
    ',"note":"\\u0421\\u0442\\u043e\\u0438\\u043c\\u043e\\u0441\\u0442\\u044c \\u043a\\u0440\\u0430\\u0444'
    '\\u0442\\u0430 \\u2014 \\u044d\\u0442\\u043e \\u0421\\u0420\\u0415\\u0414\\u041d\\u0415\\u0415 \\u043f'
    '\\u043e \\u0448\\u0430\\u043d\\u0441\\u0430\\u043c."'
    ',"marketUrl":"https://www.pathofexile.com/trade2/search/poe2/ForbiddenRites?q=%7B%7D"}'
)
note = (
    "\\u0426\\u0435\\u043d\\u0430 \\u0440\\u044b\\u043d\\u043a\\u0430: \\u043c\\u0435\\u0434\\u0438\\u0430\\u043d\\u0430 "
    "\\u043f\\u043e 18 \\u043b\\u043e\\u0442\\u0430\\u043c \\u0438\\u0437 546 \\u043d\\u0430\\u0439\\u0434\\u0435\\u043d\\u043d\\u044b\\u0445."
)
driver = driver.replace("};</script>",
                        ";showTab('step');window.showBuyVerdict(" + verdict + ',"' + note + '");};</script>')

with io.open(TARGET, "w", encoding="utf-8", newline="") as handle:
    handle.write(page.replace("</body>", driver + "</body>"))

profile = os.path.join(os.environ.get("TEMP", "."), "shotprofile-buy-link")
subprocess.run([
    CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
    "--user-data-dir=" + profile, "--window-size=1000,1000",
    "--virtual-time-budget=4000", "--screenshot=" + SHOT,
    "file:///" + TARGET.replace("\\", "/"),
], capture_output=True)

print("wrote", TARGET)
print("screenshot bytes:", os.path.getsize(SHOT) if os.path.isfile(SHOT) else "missing")
