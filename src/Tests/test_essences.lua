-- PoE2 Craft Overlay : Tests/test_essences.lua
-- Guaranteed crafts: essences always apply one specific modifier (100%), and the
-- desecration pool is weighted data from the veiled table - both are verified here.

local Parser = require("Item.Parser")
local Mods = require("Item.Mods")
local Essences = require("Item.Essences")
local Advisor = require("Craft.Advisor")
local league = require("Data.league_0_5_5")

-- Four modifiers, two of them life/mana prefixes: some essences must be blocked.
local RARE = [[
Item Class: Gloves
Rarity: Rare
Doom Grip
Blacksteel Gauntlets
--------
Item Level: 82
--------
+120 to maximum Life
+22 to maximum Mana
+45% to Fire Resistance
+38% to Cold Resistance
]]

return function(H)
	-- Data set sanity.
	local stats = Essences.stats()
	H.eq("essence: table populated", stats.essences >= 80, true)

	local rawList = require("Data.essences").list
	H.eq("essence: list length matches stats", #rawList, stats.essences)
	local malformed = 0
	for _, essence in ipairs(rawList) do
		if type(essence.name) ~= "string" or type(essence.mods) ~= "table" or not next(essence.mods) then
			malformed = malformed + 1
		end
	end
	H.eq("essence: every entry is well formed", malformed, 0)

	-- Names are the English game names: Russian was removed from the overlay.
	H.eq("essence: label is the game name",
		Essences.label("Lesser Essence of the Body"), "Lesser Essence of the Body")
	H.eq("essence: label keeps unknown names",
		Essences.label("Essence of Something New"), "Essence of Something New")

	-- Modifier keys resolve through the generated byKey index.
	local life7 = Mods.byKey("IncreasedLife7")
	H.eq("essence: modifier key resolves", life7 ~= nil, true)
	H.eq("essence: key resolves to the right group", life7 and life7.groupKey, "IncreasedLife|Prefix")
	H.eq("essence: key resolves to the right type", life7 and life7.type, "Prefix")
	H.eq("essence: key carries mod text", life7 and life7.text:find("maximum Life", 1, true) ~= nil, true)
	H.eq("essence: unknown key resolves to nil", Mods.byKey("DefinitelyNotAModKey1"), nil)

	-- Essence options for the item's class.
	local item = Mods.annotate(Parser.parse(RARE))
	local options = Essences.optionsFor(item)
	H.eq("essence: options found for gloves", #options > 0, true)
	H.eq("essence: every option is a 100% craft", options[1].chance, 100)
	H.eq("essence: options carry a resolved modifier", options[1].mod ~= nil and options[1].mod.text ~= nil, true)
	H.eq("essence: options carry the english label",
		options[1].label, options[1].name)

	-- The item already has a life prefix, so life essences must be marked blocked and
	-- sorted behind the usable ones.
	local blockedCount, firstBlocked = 0, nil
	for index, option in ipairs(options) do
		if option.blocked then
			blockedCount = blockedCount + 1
			firstBlocked = firstBlocked or index
		elseif firstBlocked then
			H.check("essence: usable options come first", false, "blocked option before a usable one")
			break
		end
	end
	H.eq("essence: blocked options detected", blockedCount > 0, true)

	local lifeOption = nil
	for _, option in ipairs(options) do
		if option.mod.groupKey == "IncreasedLife|Prefix" then
			lifeOption = option
			break
		end
	end
	H.eq("essence: life essence is blocked by the existing life mod",
		lifeOption ~= nil and lifeOption.blocked, true)

	-- A limit trims the list but keeps the best options.
	local limited = Essences.optionsFor(item, { limit = 3 })
	H.eq("essence: limit is honoured", #limited, 3)

	-- Desecration: weighted pool from the veiled table.
	local hints = Mods.hintsFor(item)
	local pool = Mods.desecrationPool(82, hints)
	H.eq("essence: desecration pool is not empty", pool.tierCount > 0, true)
	local sum = 0
	for _, entry in ipairs(pool.entries) do
		sum = sum + entry.chance
	end
	H.eq("essence: desecration chances sum to 100%", math.abs(sum - 100) < 0.001, true)
	-- The pool now comes from the official desecrated stat set, and that set *does* include
	-- ordinary modifiers such as maximum life - the old assertion here (that no IncreasedLife
	-- entry may appear) was a property of the previous, wrong source, which only carried the
	-- 36 breach-themed modifiers. What has to hold now is the rule the game enforces: a
	-- modifier the item already carries is not offered again, and that is decided by text,
	-- because the same wording can live in another group.
	local itemTexts = Mods.presentTexts(item)
	local filtered = Mods.desecrationPool(82, hints, { excludeTexts = itemTexts })
	local leaked = 0
	for _, entry in ipairs(filtered.entries or { }) do
		if itemTexts[entry.text] then
			leaked = leaked + 1
		end
	end
	H.eq("essence: desecration does not offer a modifier the item already has", leaked, 0)
	H.eq("essence: desecration still offers other modifiers", filtered.tierCount > 0, true)

	-- The advisor surfaces both: essences as guaranteed crafts and desecration with
	-- real odds instead of "not computed".
	local advice = Advisor.analyze(Parser.parse(RARE), league)
	local essenceEntries, desecration = 0, nil
	for _, option in ipairs(advice.omenOptions) do
		if option.kind == "essence" then
			essenceEntries = essenceEntries + 1
		elseif option.omenId == "sinistral_necromancy" then
			desecration = option
		end
	end
	H.eq("essence: advisor offers essence crafts", essenceEntries > 0, true)
	H.eq("essence: essence crafts are capped in the panel", essenceEntries <= 3, true)
	H.eq("essence: desecration option present", desecration ~= nil, true)
	H.eq("essence: desecration now carries computed odds",
		desecration ~= nil and desecration.pool ~= nil and desecration.pool.tierCount > 0, true)
	H.eq("essence: desecration no longer claims unknown odds",
		desecration ~= nil and desecration.oddsUnknown == false, true)
end
